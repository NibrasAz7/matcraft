/// Look up a builtin's display signature and description by name
/// (case-insensitive, like the language).
pub fn builtin_signature(name: &str) -> Option<(&'static str, &'static str)> {
    SIGNATURES.iter().find(|(n, _, _)| n.eq_ignore_ascii_case(name)).map(|(_, display, doc)| (*display, *doc))
}
